#!/usr/bin/env node
/**
 * REQ-012 FR-4b: writes the claims-and-sources table (D-2907 columns) from
 * the extractor's JSON and data/claims-sources.json.
 *
 *   node scripts/ops/extract-fact-sentences.mjs --json out/facts.json
 *   node scripts/ops/claims-table.mjs --facts out/facts.json --out product/qa/launch-review/<date>/claims-and-sources.md
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { buildRows, renderTable } from "./claims-table-lib.mjs";

const args = process.argv.slice(2);
const value = (flag) => {
  const i = args.indexOf(flag);
  return i >= 0 ? args[i + 1] : undefined;
};
const factsPath = value("--facts") ?? "out/facts.json";
const out = value("--out");
const facts = JSON.parse(readFileSync(factsPath, "utf8"));
const mapping = JSON.parse(readFileSync("data/claims-sources.json", "utf8"));
const rows = buildRows(facts.distinct, mapping.entries);
const md = [
  "# Claims and sources (REQ-012 FR-4b; D-2903, D-2907, D-2908, D-2911)",
  "",
  "Every public sentence the extractor found carrying a number, a date, a dollar amount, a time frame, a hedge word or an instrument, mapped to its source in `data/claims-sources.json` or marked UNVERIFIED. Generated by `scripts/ops/claims-table.mjs`; edit the mapping, not this file. The lawyer role reads it next; any wording change goes through D-2222.",
  "",
  renderTable(rows, { extractedAt: facts.extractedAt.slice(0, 10) }),
  "",
].join("\n");
if (out) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, md);
}
console.log(md.split("\n")[4]);
